"""ui-21st prompt library manager.

Usage:
  py -I library.py add --file RAW.txt --category landing --slug saas-template \
      --title "..." --use-when "..." [--kind component] [--tags a,b] [--source "..."] [--notes "..."]
  py -I library.py index            # rebuild library/INDEX.md (+ sync SKILL.md to Codex)
  py -I library.py check --file RAW.txt   # is this prompt already saved?
  py -I library.py hook             # Claude Code UserPromptSubmit hook (reads JSON on stdin)
"""
import argparse, datetime, hashlib, io, json, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = os.path.join(ROOT, "library")
CODEX_SKILL = os.path.join(os.path.expanduser("~"), ".codex", "skills", "ui-21st")
CATEGORIES = {
    "landing": "Landing pages & heroes",
    "sections": "Page sections (testimonials, features, carousels, bento)",
    "dashboard": "Dashboard shells, sidebars, widgets",
    "navigation": "Navbars, command menus, tabs",
    "data-viz": "Charts, stat cards, KPI widgets",
    "forms": "Forms, steppers, inputs",
    "backgrounds": "Gradients, shaders, animated backgrounds",
    "themes": "Color themes & palettes",
    "motion": "Animations & micro-interactions",
    "misc": "Everything else",
}

# A pasted prompt that looks like it came from 21st.dev (component, gradient, shader, theme builder).
PROMPT_RE = re.compile(
    r"You are given a task to integrate an existing React component"
    r"|Copy-paste this component to /components/ui"
    r"|shadcn project structure"
    r"|Add an animated WebGL shader background"
    r"|21st\.dev Shader Builder"
    r"|Recreate the \"[^\"]{1,60}\" gradient"
    r"|21st\.dev/(community|@)",
    re.I,
)
# The user asking to improve / redesign a web app's UI (Indonesian + English).
UI_RE = re.compile(
    r"\bui[ -/]?ux\b|\bimprove\b.{0,30}\b(ui|ux|design|tampilan|landing|dashboard)"
    r"|\b(perbaiki|percantik|perindah|memperindah|rombak|rapihin|benerin)\b.{0,30}\b(ui|tampilan|desain|design|landing|dashboard|layout)"
    r"|\b(redesign|revamp|restyle)\b|\bpolish\b.{0,20}\b(ui|design)"
    r"|\b(bikin|buat|bikinin)(in)?\b.{0,20}\blanding ?page"
    r"|\bvisual cue|\bsistem design\b|\bdesign system\b",
    re.I,
)


def norm(text):
    """Undo the one-backtick-per-line mangling some pastes get, normalise newlines."""
    out = []
    for line in text.replace("\r", "").split("\n"):
        m = re.match(r"^`(.*)`$", line)
        out.append(m.group(1) if m and "```" not in line else line)
    return "\n".join(out).strip()


def fingerprint(text):
    return hashlib.md5(re.sub(r"\s+", "", norm(text)).encode("utf-8")).hexdigest()[:12]


def read_entries():
    entries = []
    for cat in sorted(os.listdir(LIB)) if os.path.isdir(LIB) else []:
        d = os.path.join(LIB, cat)
        if not os.path.isdir(d):
            continue
        for fn in sorted(os.listdir(d)):
            if not fn.endswith(".md"):
                continue
            path = os.path.join(d, fn)
            text = open(path, encoding="utf-8").read()
            m = re.match(r"---\n(.*?)\n---\n", text, re.S)
            meta = {}
            if m:
                for line in m.group(1).split("\n"):
                    if ":" in line:
                        k, v = line.split(":", 1)
                        meta[k.strip()] = v.strip()
            meta["_path"] = os.path.relpath(path, ROOT).replace("\\", "/")
            meta.setdefault("category", cat)
            entries.append(meta)
    return entries


def known_hashes():
    return {e.get("hash") for e in read_entries() if e.get("hash")}


def cmd_index(_args=None):
    entries = read_entries()
    lines = [
        "# ui-21st library index",
        "",
        "Generated by `scripts/library.py index`. Do not edit by hand.",
        "Open an entry file only after you've picked it; each one holds the full original prompt.",
        "",
    ]
    by_cat = {}
    for e in entries:
        by_cat.setdefault(e["category"], []).append(e)
    for cat in list(CATEGORIES) + sorted(set(by_cat) - set(CATEGORIES)):
        if cat not in by_cat:
            continue
        lines += [f"## {cat} — {CATEGORIES.get(cat, cat)}", "", "| Entry | Kind | Use when | Deps | File |", "|---|---|---|---|---|"]
        for e in by_cat[cat]:
            lines.append(
                f"| **{e.get('title', e.get('name'))}** | {e.get('kind', '')} | {e.get('use_when', '')} "
                f"| {e.get('deps', '') or '-'} | `{e['_path']}` |"
            )
        lines.append("")
    lines.append(f"_{len(entries)} entries._")
    os.makedirs(LIB, exist_ok=True)
    open(os.path.join(LIB, "INDEX.md"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    # Keep the Codex copy of the skill pointing at this same library.
    if os.path.isdir(os.path.dirname(CODEX_SKILL)):
        os.makedirs(CODEX_SKILL, exist_ok=True)
        shutil.copyfile(os.path.join(ROOT, "SKILL.md"), os.path.join(CODEX_SKILL, "SKILL.md"))
    print(f"INDEX.md rebuilt: {len(entries)} entries")


def detect_deps(raw):
    m = re.search(r"Install NPM dependencies:\s*(?:```\w*)?\s*([^`]+?)(?:```|\n\n)", raw)
    return re.sub(r"\s+", " ", m.group(1)).strip().strip(",") if m else ""


def cmd_add(a):
    raw = norm(open(a.file, encoding="utf-8").read())
    h = fingerprint(raw)
    for e in read_entries():
        if e.get("hash") == h:
            print(f"Already in library: {e['_path']}")
            return
    if a.category not in CATEGORIES:
        sys.exit(f"Unknown category {a.category!r}. Use one of: {', '.join(CATEGORIES)}")
    slug = re.sub(r"[^a-z0-9-]+", "-", a.slug.lower()).strip("-")
    path = os.path.join(LIB, a.category, slug + ".md")
    if os.path.exists(path):
        sys.exit(f"{path} exists; pick another --slug")
    fm = re.search(r"Copy-paste this component to /components/ui folder:\s*(?:```\w*\s*)?([\w.-]+\.(?:tsx|jsx|ts))", raw)
    meta = {
        "name": slug,
        "title": a.title,
        "category": a.category,
        "kind": a.kind,
        "file": fm.group(1) if fm else "",
        "deps": a.deps if a.deps is not None else detect_deps(raw),
        "tags": a.tags,
        "use_when": a.use_when,
        "source": a.source,
        "url": a.url,
        "hash": h,
        "added": datetime.date.today().isoformat(),
    }
    head = "---\n" + "\n".join(f"{k}: {v}" for k, v in meta.items() if v) + "\n---\n"
    body = f"\n# {a.title}\n\n## Notes\n\n{a.notes or '-'}\n\n## Original prompt (verbatim)\n\n" + raw + "\n"
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write(head + body)
    print(f"Saved {os.path.relpath(path, ROOT)}")
    cmd_index()


def cmd_check(a):
    h = fingerprint(open(a.file, encoding="utf-8").read())
    hit = [e["_path"] for e in read_entries() if e.get("hash") == h]
    print(f"SAVED {hit[0]}" if hit else f"NEW {h}")


def split_prompts(text):
    """Split a paste that may hold several 21st prompts into individual chunks."""
    text = norm(text)
    starts = []
    for m in re.finditer(r"You are given a task to integrate|The codebase should support:|Add an animated WebGL shader|Recreate the \"", text):
        # "The codebase should support:" opens a prompt only when no "You are given..." line sits right above it.
        if m.group().startswith("The codebase") and "You are given a task" in text[max(0, m.start() - 200):m.start()]:
            continue
        starts.append(m.start())
    return [text[s:e].split("</pasted_content")[0].strip() for s, e in zip(starts, starts[1:] + [len(text)])]


def cmd_hook(_a):
    try:
        data = json.load(io.TextIOWrapper(sys.stdin.buffer, encoding="utf-8"))
    except Exception:
        return
    prompt = data.get("prompt", "") or ""
    texts = [prompt]
    # @"C:\...\message.txt" attachments: read them too, that's how long prompts usually arrive.
    for p in re.findall(r'@"([^"]+\.(?:txt|md))"', prompt) + re.findall(r"@(\S+\.(?:txt|md))", prompt):
        try:
            texts.append(open(p, encoding="utf-8", errors="ignore").read())
        except OSError:
            pass
    notes = []
    known = known_hashes()
    new = []
    for t in texts:
        if PROMPT_RE.search(t):
            for chunk in split_prompts(t) or [t]:
                if PROMPT_RE.search(chunk) and fingerprint(chunk) not in known:
                    m = re.search(r"([\w.-]+\.tsx)|Recreate the \"([^\"]+)\"|Style: \"([^\"]+)\"", chunk)
                    new.append(next((g for g in (m.groups() if m else ()) if g), "unnamed prompt"))
    if new:
        notes.append(
            "[ui-21st] This message contains 21st.dev-style design prompt(s) not yet in the library: "
            + ", ".join(dict.fromkeys(new))
            + ". Follow the user's actual request first. Then, before the turn ends, ASK the user whether to save them "
            "(propose slug, category, title, use-when for each). Only on a yes, write each raw prompt to a temp file and run "
            "`py -I \"C:/Users/Raphael Angelo/.claude/skills/ui-21st/scripts/library.py\" add ...` (see the ui-21st skill, section 'Saving new prompts')."
        )
    if UI_RE.search(prompt) or new:
        notes.append(
            "[ui-21st] If this is UI/UX improvement or design work on a web app, load the `ui-21st` skill first "
            "(understand the app, then match prompts from its library) unless it is already loaded in this session."
        )
    if notes:
        print(json.dumps({"hookSpecificOutput": {"hookEventName": "UserPromptSubmit", "additionalContext": "\n".join(notes)}}))


def main():
    sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("add")
    p.add_argument("--file", required=True)
    p.add_argument("--category", required=True)
    p.add_argument("--slug", required=True)
    p.add_argument("--title", required=True)
    p.add_argument("--use-when", required=True)
    p.add_argument("--kind", default="component")
    p.add_argument("--tags", default="")
    p.add_argument("--deps", default=None)
    p.add_argument("--source", default="")
    p.add_argument("--url", default="")
    p.add_argument("--notes", default="")
    sub.add_parser("index")
    c = sub.add_parser("check")
    c.add_argument("--file", required=True)
    sub.add_parser("hook")
    a = ap.parse_args()
    {"add": cmd_add, "index": cmd_index, "check": cmd_check, "hook": cmd_hook}[a.cmd](a)


if __name__ == "__main__":
    main()
